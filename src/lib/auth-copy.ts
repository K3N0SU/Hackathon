export type AuthError = keyof (typeof authCopy)["en"]["errors"];

export function authError(error: unknown): AuthError {
  const code =
    typeof error === "object" && error && "code" in error
      ? String(error.code)
      : "";
  if (
    code === "auth/invalid-credential" ||
    code === "auth/wrong-password" ||
    code === "auth/user-not-found"
  )
    return "invalid";
  if (code === "auth/email-already-in-use") return "inUse";
  if (code === "auth/weak-password") return "weak";
  if (code === "auth/invalid-email" || code === "auth/missing-email")
    return "badEmail";
  if (
    code === "auth/popup-closed-by-user" ||
    code === "auth/cancelled-popup-request"
  )
    return "popup";
  if (code === "auth/too-many-requests") return "tooMany";
  if (code === "auth/network-request-failed") return "network";
  if (
    code === "auth/invalid-api-key" ||
    code === "auth/configuration-not-found"
  )
    return "notConfigured";
  if (code === "auth/unauthorized-domain") return "wrongSite";
  return "generic";
}
